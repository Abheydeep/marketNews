export function assertPublicBriefingCopy(label, value) {
  const violations = findPublicBriefingViolations(label, value);
  if (violations.length) {
    const details = violations
      .map((violation) => `- ${violation.label}: "${violation.excerpt}"`)
      .join("\n");
    throw new Error(`Public editorial guardrail failed.\n${details}`);
  }
}

export function assertReelScriptCopy(label, value) {
  const text = String(value ?? "");
  const violations = [];
  for (const pattern of REEL_FORBIDDEN_PATTERNS) {
    pattern.lastIndex = 0;
    const match = pattern.exec(text);
    if (match) {
      violations.push({
        label,
        pattern: pattern.toString(),
        excerpt: excerptAround(text, match.index, match[0].length)
      });
    }
  }
  const required = ["ON SCREEN:", "VOICEOVER:", "[0-03s | HOOK]", "[40-52s | TRADE PLAN]"];
  for (const phrase of required) {
    if (!text.includes(phrase)) {
      violations.push({
        label,
        pattern: phrase,
        excerpt: "missing required reel structure"
      });
    }
  }
  if (violations.length) {
    const details = violations
      .map((violation) => `- ${violation.label}: "${violation.excerpt}"`)
      .join("\n");
    throw new Error(`Reel script editorial guardrail failed.\n${details}`);
  }
}

export function sanitizeLegacyPublicBriefingCopy(value) {
  if (typeof value === "string") {
    return sanitizeString(value);
  }

  if (Array.isArray(value)) {
    return value.map((item) => sanitizeLegacyPublicBriefingCopy(item));
  }

  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value).map(([key, item]) => [key, sanitizeLegacyPublicBriefingCopy(item)])
    );
  }

  return value;
}

export function findPublicBriefingViolations(label, value) {
  const text = String(value ?? "");
  const violations = [];

  for (const pattern of PUBLIC_FORBIDDEN_PATTERNS) {
    pattern.lastIndex = 0;
    const match = pattern.exec(text);
    if (!match) {
      continue;
    }
    violations.push({
      label,
      pattern: pattern.toString(),
      excerpt: excerptAround(text, match.index, match[0].length)
    });
  }

  return violations;
}

function excerptAround(text, index, length) {
  const start = Math.max(0, index - 48);
  const end = Math.min(text.length, index + length + 48);
  return text
    .slice(start, end)
    .replace(/\s+/g, " ")
    .trim();
}

function sanitizeString(value) {
  return value
    .replace(
      /Two-minute read:\s*this briefing distills[^.]*\.\s*/gi,
      ""
    )
    .replace(
      /This briefing is built from\s+\d+\s+source notes,\s+\d+\s+narrative clusters,\s+and\s+\d+\s+market snapshots\.\s*/gi,
      ""
    )
    .replace(
      /The scanner has deliberately removed stale trade levels after live quote validation, so the video should frame the first hour as a level-discovery phase rather than a ready-made trade call\./gi,
      "No clean 1:2 setup is active yet, so use the first hour to watch opening-range acceptance before taking a directional view."
    )
    .replace(
      /No active 1:2 RR setup passed all scanner and live-quote filters\./gi,
      "No clean 1:2 RR setup is active yet; wait for fresh opening-range confirmation."
    )
    .replace(
      /No trade setup qualifies under the 1:2 risk-reward framework after live quote validation\./gi,
      "No clean 1:2 setup is active yet; wait for the opening range to confirm direction."
    )
    .replace(
      /Avoid chasing the first candle; let Nifty and Bank Nifty prove acceptance near the scanner levels\./gi,
      "Avoid chasing the first candle; let Nifty and Bank Nifty prove acceptance around the opening range."
    )
    .replace(
      /Live quote validation removed stale 1:2 levels\./gi,
      "Wait for opening-range confirmation."
    )
    .replace(
      /Live validation removed stale levels\./gi,
      "Waiting for fresh levels."
    )
    .replace(
      /No active setup after live quote validation; stale levels are hidden from the studio\./gi,
      "No active setup yet; outdated levels are hidden from the studio."
    );
}
