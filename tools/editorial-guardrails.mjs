export function assertPublicBriefingCopy(label, value) {
  const violations = findPublicBriefingViolations(label, value);
  if (violations.length) {
    const details = violations
      .map((violation) => `- ${violation.label}: "${violation.excerpt}"`)
      .join("\n");
    throw new Error(`Public editorial guardrail failed.\n${details}`);
  }
}

export function assertReelScriptCopy(label, value) {
  const text = String(value ?? "");
  const violations = [];
  for (const pattern of REEL_FORBIDDEN_PATTERNS) {
    pattern.lastIndex = 0;
    const match = pattern.exec(text);
    if (match) {
      violations.push({
        label,
        pattern: pattern.toString(),
        excerpt: excerptAround(text, match.index, match[0].length)
      });
    }
  }
  const required = ["ON SCREEN:", "VOICEOVER:", "[0-03s | HOOK]", "[40-52s | TRADE PLAN]"];
  for (const phrase of required) {
    if (!text.includes(phrase)) {
      violations.push({
        label,
        pattern: phrase,
        excerpt: "missing required reel structure"
      });
    }
  }
  if (violations.length) {
    const details = violations
      .map((violation) => `- ${violation.label}: "${violation.excerpt}"`)
      .join("\n");
    throw new Error(`Reel script editorial guardrail failed.\n${details}`);
  }
}

export function sanitizeLegacyPublicBriefingCopy(value) {
  if (typeof value === "string") {
    return sanitizeString(value);
  }

  if (Array.isArray(value)) {
    return value.map((item) => sanitizeLegacyPublicBriefingCopy(item));
  }

  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value).map(([key, item]) => [key, sanitizeLegacyPublicBriefingCopy(item)])
    );
  }

  return value;
}

export function findPublicBriefingViolations(label, value) {
  const text = String(value ?? "");
  const violations = [];

  for (const pattern of PUBLIC_FORBIDDEN_PATTERNS) {
    pattern.lastIndex = 0;
    const match = pattern.exec(text);
    if (!match) {
      continue;
    }
    violations.push({
      label,
      pattern: pattern.toString(),
      excerpt: excerptAround(text, match.index, match[0].length)
    });
  }

  return violations;
}

function excerptAround(text, index, length) {
  const start = Math.max(0, index - 48);
  const end = Math.min(text.length, index + length + 48);
  return text
    .slice(start, end)
    .replace(/\s+/g, " ")
    .trim();
}

function sanitizeString(value) {
  return value
    .replace(
      /Two-minute read:\s*this briefing distills[^.]*\.\s*/gi,
      ""
    )
    .replace(
      /This briefing is built from\s+\d+\s+source notes,\s+\d+\s+narrative clusters,\s+and\s+\d+\s+market snapshots\.\s*/gi,
      ""
    )
    .replace(
      /Global Pressure Meets Domestic Selectivity/gi,
      "Global Risk Tests Domestic Breadth"
    )
    .replace(
      /Educational note: This summary is for market research and content preparation only, not financial advice\./gi,
      "Educational note: Educational market research only. This is not SEBI-registered investment advice, a research recommendation, or a solicitation to buy or sell securities or derivatives. No returns are assured; use your own risk plan."
    )
    .replace(
      /The scanner has deliberately removed stale trade levels after live quote validation, so the video should frame the first hour as a level-discovery phase rather than a ready-made trade call\./gi,
      "No clean 1:2 setup is active yet, so use the first hour to watch opening-range acceptance before taking a directional view."
    )
    .replace(
      /No active 1:2 RR setup passed all scanner and live-quote filters\./gi,
      "No clean 1:2 RR setup is active yet; wait for fresh opening-range confirmation."
    )
    .replace(
      /No trade setup qualifies under the 1:2 risk-reward framework after live quote validation\./gi,
      "No clean 1:2 setup is active yet; wait for the opening range to confirm direction."
    )
    .replace(
      /Avoid chasing the first candle; let Nifty and Bank Nifty prove acceptance near the scanner levels\./gi,
      "Avoid chasing the first candle; let Nifty and Bank Nifty prove acceptance around the opening range."
    )
    .replace(
      /No direct India read-through for this story\./gi,
      "Global-only context: no direct India trade read; use it only if index futures, sector breadth, currency, or rates confirm after the open."
    )
    .replace(
      /Watch USD\/INR near 84\.20 and DXY in the first hour; pressure splits exporters from importers\./gi,
      "Watch spot USD/INR against its morning range and DXY in the first hour; pressure splits exporters from importers."
    )
    .replace(
      /after 10:15 AM IST/gi,
      "through 9:45-10:00 AM IST"
    )
    .replace(
      /Watch Market during the first-hour range;\s*trade it only if it broadens into sector leadership\.?/gi,
      "Watch first-range high/low, VWAP, advance-decline, and Bank Nifty breadth through 9:45-10:00 AM IST."
    )
    .replace(
      /Watch ([A-Za-z][A-Za-z\s/&+-]{1,40}) during the first-hour range;\s*trade it only if it broadens into sector leadership\.?/gi,
      (_match, entity) => `Watch ${entity.trim()} peer breadth after 9:45 AM; no index bias unless banks and Nifty hold VWAP.`
    )
    .replace(
      /([A-Za-z][A-Za-z\s/&+-]{1,40}) is only a conditional India input;\s*require first-range breadth and related sector participation before using it for trade bias\.?/gi,
      (_match, entity) => `${entity.trim()} needs related Indian peer breadth before it becomes more than a watchlist cue.`
    )
    .replace(
      /use it as a ([A-Za-z][A-Za-z\s/&+-]{1,40}) watch input only if a related Indian sector confirms the move\.?/gi,
      (_match, entity) => `treat ${entity.trim()} as a watchlist cue only after related Indian sector breadth confirms.`
    )
    .replace(
      /([A-Za-z][A-Za-z\s/&+-]{1,40}) is a watch input,\s*not a trade bias,\s*until Nifty breadth and Bank Nifty confirm\.?/gi,
      (_match, entity) => `${entity.trim()} stays on the watchlist until Nifty breadth and Bank Nifty confirm.`
    )
    .replace(
      /Live quote validation removed stale 1:2 levels\./gi,
      "Wait for opening-range confirmation."
    )
    .replace(
      /Live validation removed stale levels\./gi,
      "Waiting for fresh levels."
    )
    .replace(
      /No active setup after live quote validation; stale levels are hidden from the studio\./gi,
      "No active setup yet; outdated levels are hidden from the studio."
    );
}
