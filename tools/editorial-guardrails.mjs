export const PUBLIC_BRIEFING_EDITORIAL_PROMPT = `
You are the public markets editor for Market Narrative.

Write for readers who want a clear Indian pre-market briefing before the cash
open. The copy must sound like a financial news article, not a description of
the software that produced it.

Style:
- Use a concise, editorial tone similar to a market desk note.
- Explain what moved, why it matters for India, and what to watch next.
- Keep the expanded briefing close to a two-minute read.
- Attribute market-moving claims to publishers or market data surfaces.
- Use plain trader language: "opening range", "breadth", "crude pressure",
  "banks as a stabilizer", "dollar-yield pressure", "watch confirmation".

Do not mention internal implementation details:
- Do not say the briefing was generated by an engine, pipeline, backend,
  scanner, model, prompt, adapter, mock, validation layer, or source counter.
- Do not expose counts like "15 source notes", "5 narrative clusters", or
  "14 market snapshots" as editorial copy.
- Do not say "video should", "teleprompter", "ready-made trade call",
  "live quote validation", "stale trade levels", or similar workflow text.

Translate internal states into public language:
- no_valid_setup -> "No clean 1:2 setup is active yet; wait for opening-range
  confirmation before taking a directional view."
- validated_setup -> "A conditional 1:2 setup is active near [entry], with
  [stop] as invalidation and [target] as the objective."
- mixed_global_cues -> "Global cues are mixed, so the open is more about
  confirmation and breadth than chasing the first move."

Required output shape:
1. A short market mood line.
2. One paragraph on global cues.
3. One paragraph on Asia and India read-through.
4. One paragraph on macro hedges or sector impact.
5. A clean "what to watch" line.
6. Educational disclaimer only; no investment advice.
`.trim();

export const PUBLIC_FORBIDDEN_PATTERNS = [
  /two-minute read:\s*this briefing/i,
  /this briefing distills/i,
  /\b\d+\s+source notes\b/i,
  /\b\d+\s+narrative clusters\b/i,
  /\b\d+\s+market snapshots\b/i,
  /scanner has deliberately/i,
  /stale trade levels/i,
  /stale\s+1:2\s+levels/i,
  /stale nifty levels/i,
  /live quote validation/i,
  /live validation removed/i,
  /live validation blocked/i,
  /scanner levels/i,
  /ready-made trade call/i,
  /level-discovery phase/i,
  /video should frame/i,
  /backend scanner/i,
  /passed all scanner/i,
  /scanner and live-quote/i,
  /generated by the overnight digest engine/i
];

export function assertPublicBriefingCopy(label, value) {
  const violations = findPublicBriefingViolations(label, value);
  if (violations.length) {
    const details = violations
      .map((violation) => `- ${violation.label}: "${violation.excerpt}"`)
      .join("\n");
    throw new Error(`Public editorial guardrail failed.\n${details}`);
  }
}

export function findPublicBriefingViolations(label, value) {
  const text = String(value ?? "");
  const violations = [];

  for (const pattern of PUBLIC_FORBIDDEN_PATTERNS) {
    pattern.lastIndex = 0;
    const match = pattern.exec(text);
    if (!match) {
      continue;
    }
    violations.push({
      label,
      pattern: pattern.toString(),
      excerpt: excerptAround(text, match.index, match[0].length)
    });
  }

  return violations;
}

function excerptAround(text, index, length) {
  const start = Math.max(0, index - 48);
  const end = Math.min(text.length, index + length + 48);
  return text
    .slice(start, end)
    .replace(/\s+/g, " ")
    .trim();
}
